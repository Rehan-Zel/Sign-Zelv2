enum class Screen { SETTINGS, BUILDER, PREVIEW, PUSH, LOGS }

enum class Check { IDLE, RUNNING, OK, FAIL }

class AppViewModel(app: Application) : AndroidViewModel(app) {

    private val prefs = app.getSharedPreferences("sign_zel", Context.MODE_PRIVATE)

    // ───── Navigation ─────
    var screen by mutableStateOf(Screen.SETTINGS)

    // ───── Settings ─────
    var pat by mutableStateOf(prefs.getString("pat", "") ?: "")
    var aiKey by mutableStateOf(prefs.getString("aiKey", "") ?: "")
    var aiBaseUrl by mutableStateOf(prefs.getString("aiBase", "https://openrouter.ai/api/v1") ?: "")
    var aiModel by mutableStateOf(prefs.getString("aiModel", "openai/gpt-4o-mini") ?: "")
    var themeMode by mutableStateOf(
        runCatching { ThemeMode.valueOf(prefs.getString("theme", "DARK") ?: "DARK") }.getOrDefault(ThemeMode.DARK)
    )

    var ghCheck by mutableStateOf(Check.IDLE)
    var aiCheck by mutableStateOf(Check.IDLE)
    var ghMsg by mutableStateOf("")
    var aiMsg by mutableStateOf("")

    fun save() {
        prefs.edit()
            .putString("pat", pat)
            .putString("aiKey", aiKey)
            .putString("aiBase", aiBaseUrl)
            .putString("aiModel", aiModel)
            .putString("theme", themeMode.name)
            .apply()
    }

    private fun aiCfg() = AiConfig(aiKey.trim(), aiBaseUrl.trim(), aiModel.trim())

    fun validate() {
        save()
        ghCheck = Check.RUNNING
        aiCheck = Check.RUNNING
        ghMsg = ""
        aiMsg = ""
        viewModelScope.launch {
            val gh = async { runCatching { ApiClient.validateGithub(pat.trim()) } }
            val ai = async { runCatching { ApiClient.pingAi(aiCfg()) } }
            gh.await()
                .onSuccess { ghCheck = Check.OK; ghMsg = "Authenticated as $it" }
                .onFailure { ghCheck = Check.FAIL; ghMsg = it.message ?: "Failed" }
            ai.await()
                .onSuccess { aiCheck = Check.OK; aiMsg = "AI replied: ${it.trim().take(40)}" }
                .onFailure { aiCheck = Check.FAIL; aiMsg = it.message ?: "Failed" }
        }
    }

    // ───── Builder inputs ─────
    var sourceUri by mutableStateOf<Uri?>(null)
    var sourceIsTree by mutableStateOf(false)
    var sourceName by mutableStateOf("")
    var appName by mutableStateOf("")
    var iconUri by mutableStateOf<Uri?>(null)
    var splashUri by mutableStateOf<Uri?>(null)

    var busy by mutableStateOf(false)
    var status by mutableStateOf("")
    var errorMsg by mutableStateOf("")

    fun setSource(uri: Uri, isTree: Boolean) {
        val ctx = getApplication<Application>()
        sourceUri = uri
        sourceIsTree = isTree
        sourceName = if (isTree) ProjectReader.treeName(ctx, uri) else ProjectReader.displayName(ctx, uri)
        errorMsg = ""
    }

    // ───── Analysis result ─────
    var files by mutableStateOf<Map<String, ByteArray>>(emptyMap())
    var generated by mutableStateOf<Set<String>>(emptySet())
    var summary by mutableStateOf("")

    fun analyze() {
        val src = sourceUri
        if (src == null) {
            errorMsg = "Pick a ZIP, HTML file or folder first."
            return
        }
        save()
        errorMsg = ""
        busy = true
        viewModelScope.launch {
            try {
                val ctx = getApplication<Application>()
                status = "Reading files…"
                val orig = withContext(Dispatchers.IO) {
                    if (sourceIsTree) ProjectReader.readTree(ctx, src) else ProjectReader.readFile(ctx, src)
                }
                if (orig.isEmpty()) throw ApiException("No files found in the selection.")

                status = "Scanning for Gradle / manifest files…"
                val isWeb = !ProjectScanner.hasAndroid(orig)
                val base: Map<String, ByteArray> = if (isWeb) ProjectScanner.relocateWeb(orig) else orig
                val entry = if (isWeb) ProjectScanner.webEntry(base) else ""

                val result = LinkedHashMap<String, ByteArray>(base)
                val gen = linkedSetOf<String>()

                var hasIcon = false
                var hasSplash = false
                val iu = iconUri
                if (iu != null) {
                    status = "Processing custom icon…"
                    val png = withContext(Dispatchers.IO) { ProjectReader.toPng(ctx, iu, 192, true) }
                    val p = "app/src/main/res/mipmap-xxxhdpi/ic_launcher.png"
                    result[p] = png; gen.add(p); hasIcon = true
                }
                val su = splashUri
                if (su != null) {
                    status = "Processing splash screen…"
                    val png = withContext(Dispatchers.IO) { ProjectReader.toPng(ctx, su, 1280, false) }
                    val p = "app/src/main/res/drawable/splash.png"
                    result[p] = png; gen.add(p); hasSplash = true
                }

                val missing = ProjectScanner.missing(result)
                var aiSummary = ""
                if (missing.isNotEmpty()) {
                    if (aiKey.isBlank()) throw ApiException("Files are missing (${missing.joinToString()}) – set your AI key in Settings.")
                    status = "AI is generating missing files…"
                    val r = AiAssistant.generate(aiCfg(), appName.trim(), isWeb, entry, missing, result, hasIcon, hasSplash)
                    aiSummary = r.summary.orEmpty()
                    for ((p, b) in AiAssistant.filesOf(r)) {
                        if (!result.containsKey(p)) {
                            result[p] = b; gen.add(p)
                        }
                    }
                }

                if (!result.containsKey("gradle.properties")) {
                    result["gradle.properties"] = Templates.GRADLE_PROPERTIES.toByteArray(); gen.add("gradle.properties")
                }
                if (!result.containsKey(Templates.WORKFLOW_PATH)) {
                    result[Templates.WORKFLOW_PATH] = Templates.WORKFLOW.toByteArray(); gen.add(Templates.WORKFLOW_PATH)
                }

                files = result
                generated = gen
                summary = buildString {
                    append(if (isWeb) "Detected a web project – wrapped into a WebView app (entry: $entry).\n"
                    else "Detected an existing Android project.\n")
                    append(if (missing.isEmpty()) "Nothing essential was missing.\n"
                    else "Missing: ${missing.joinToString()}\n")
                    append("Icon: ").append(if (hasIcon) "custom" else "AI-generated").append(" · Splash: ")
                        .append(if (hasSplash) "custom" else "AI-generated").append('\n')
                    if (aiSummary.isNotBlank()) append("\nAI: ").append(aiSummary)
                }
                if (repoName.isBlank()) {
                    repoName = "zel-" + ProjectScanner.slug(appName.ifBlank { sourceName.substringBeforeLast('.') })
                }
                screen = Screen.PREVIEW
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                errorMsg = e.message ?: e.toString()
            } finally {
                busy = false
                status = ""
            }
        }
    }

    // ───── Push & build ─────
    var repoName by mutableStateOf("")
    var privateRepo by mutableStateOf(false)
    val logs = mutableStateListOf<String>()
    var building by mutableStateOf(false)
    var apkUrl by mutableStateOf<String?>(null)
    var repoUrl by mutableStateOf<String?>(null)
    private var job: Job? = null

    private fun log(s: String) {
        logs.add(s)
    }

    fun stopBuild() {
        job?.cancel()
        building = false
        log("■ Stopped by user.")
    }

    fun pushAndBuild() {
        if (building) {
            screen = Screen.LOGS
            return
        }
        if (files.isEmpty()) {
            errorMsg = "Analyze a project first."
            return
        }
        if (repoName.isBlank()) return
        save()
        logs.clear()
        apkUrl = null
        building = true
        screen = Screen.LOGS
        job = viewModelScope.launch {
            try {
                val token = pat.trim()
                val name = repoName.trim().replace(Regex("[^A-Za-z0-9._-]"), "-")
                log("$ creating repository '$name'…")
                val repo = ApiClient.createRepo(token, name, privateRepo)
                repoUrl = repo.htmlUrl
                log("✓ repo ready: ${repo.htmlUrl}")

                val current = LinkedHashMap<String, ByteArray>(files)
                log("$ uploading ${current.size} files in one commit…")
                var sha = ApiClient.commitFiles(token, repo, current, "Sign Zel: initial project")
                log("✓ pushed commit ${sha.take(7)}")

                var attempt = 0
                val maxHeals = 5
                while (true) {
                    val finalRun = followRun(token, repo, sha)
                    if (finalRun.conclusion == "success") {
                        apkUrl = finalRun.htmlUrl
                        log("✓ BUILD SUCCESSFUL – APK is in the run's artifacts (app-debug).")
                        break
                    }
                    log("✗ Failed! (conclusion: ${finalRun.conclusion ?: "unknown"})")
                    if (attempt >= maxHeals) {
                        log("✗ Giving up after $maxHeals auto-heal attempts. Check: ${finalRun.htmlUrl}")
                        break
                    }
                    attempt++
                    log("$ fetching logs…")
                    val errors = ApiClient.failureLogs(token, repo, finalRun.id)
                    if (errors.isBlank()) {
                        log("✗ No failed-job logs available. See ${finalRun.htmlUrl}")
                        break
                    }
                    errors.lines().filter { it.isNotBlank() }.takeLast(12).forEach { log("  $it") }
                    log("[AI] Auto-Heal attempt $attempt/$maxHeals – asking the model for a fix…")
                    val fix = AiAssistant.heal(aiCfg(), errors, current)
                    val changed = AiAssistant.filesOf(fix)
                    if (changed.isEmpty()) {
                        log("✗ AI returned no file changes. Stopping.")
                        break
                    }
                    log("[AI] ${fix.summary.orEmpty().take(300)}")
                    for ((p, b) in changed) {
                        current[p] = b
                        log("[AI] patched $p")
                    }
                    files = LinkedHashMap(current)
                    generated = generated + changed.keys
                    log("$ pushing fix…")
                    sha = ApiClient.commitFiles(token, repo, current, "Sign Zel auto-heal #$attempt")
                    log("✓ pushed commit ${sha.take(7)} – restarting build")
                }
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                log("✗ Error: ${e.message ?: e.toString()}")
            } finally {
                building = false
            }
        }
    }

    /** Waits for the workflow run belonging to [sha] and polls until completion. */
    private suspend fun followRun(token: String, repo: RepoInfo, sha: String): RunInfo {
        log("… waiting for GitHub Actions to start the workflow")
        var run: RunInfo? = null
        for (i in 0 until 15) {
            run = ApiClient.findRunForSha(token, repo, sha)
            if (run != null) break
            delay(3000)
        }
        if (run == null) {
            log("… no run triggered by push – dispatching manually")
            ApiClient.dispatchWorkflow(token, repo)
            delay(6000)
            run = ApiClient.latestRun(token, repo)
        }
        val started: RunInfo = run ?: throw ApiException("No workflow run found. Is Actions enabled / does the token have 'workflow' scope?")
        log("✓ run #${started.id} found")

        var last = ""
        var ticks = 0
        while (true) {
            val r = ApiClient.getRun(token, repo, started.id)
            val st = if (r.status == "completed") "completed" else r.status
            if (st != last) {
                last = st
                when (st) {
                    "queued", "waiting", "pending" -> log("… queued")
                    "in_progress" -> log("⚙ Building…")
                    "completed" -> log("… run completed")
                    else -> log("… status: $st")
                }
            } else if (ticks > 0 && ticks % 5 == 0 && r.status != "completed") {
                log("  still ${if (r.status == "in_progress") "building" else r.status}… (${ticks * 8}s)")
            }
            if (r.status == "completed") return r
            ticks++
            delay(8000)
        }
    }
}
